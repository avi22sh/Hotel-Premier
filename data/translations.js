  // Helper method to get text
  getText(key, fallback = '') {
    const lang = this.currentLang || 'en';
    if (this.translations[lang] && this.translations[lang][key]) {
      return this.translations[lang][key];
    }
    if (this.translations['en'] && this.translations['en'][key]) {
      return this.translations['en'][key];
    }
    return fallback || key;
  },

  getCategoryName(catId) {
    const lang = this.currentLang || 'en';
    const catData = this.categories[catId];
    if (catData) {
      if (lang === 'en') return catData['en'];
      return catData[lang] || catData['en'];
    }
    return catId;
  },

  getCategorySubtitle(catId) {
    const lang = this.currentLang || 'en';
    const catData = this.categories[catId];
    if (catData) {
      if (lang === 'en') return '';
      if (lang === 'hi') return catData['hi'] || '';
      if (lang === 'mr') return catData['mr'] || '';
    }
    return '';
  },

  getCategoryDescription(catId) {
    const lang = this.currentLang || 'en';
    const catData = this.categories[catId];
    if (catData) {
      return catData[`desc_${lang}`] || catData['desc_en'] || '';
    }
    return '';
  }

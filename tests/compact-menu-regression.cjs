const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('app.js', 'utf8');
const context = { window: {}, document: { readyState: 'loading', addEventListener() {} }, console };
vm.createContext(context);
vm.runInContext(source + ';window.App = HotelPremierApp;', context);
const app = Object.create(context.window.App.prototype);
app.currentLang = 'en';
app.t = (key, fallback) => fallback || key;
const dish = {id:'test',name:'Paneer Tikka',price:250,image:'assets/photo.jpg',description:'Original description',variants:[{name:'Half',price:150}]};
const card = app.renderDishCard(dish);
assert.match(card, /compact-dish-card/);
assert.match(card, /Paneer Tikka/);
assert.match(card, /₹250/);
assert.match(card, /Portion options available/);
assert.doesNotMatch(card, /Original description|class="dish-desc"|class="variant-btn/);
assert.match(source, /class="modal-dish-desc">\$\{this.getDishDescription\(dish\)/);
assert.match(source, /\$\{modalVariantsHtml\}/);
assert.match(app.renderDishCard({...dish,image:'',isSoldOut:true}), /no-photo/);
assert.match(app.renderDishCard({...dish,image:'',isSoldOut:true}), /sold-out/);
console.log('PASS: compact photo/name/price cards; descriptions and portions retained in details; sold-out and empty photos supported');

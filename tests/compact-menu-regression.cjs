const context = { window: {}, document: { readyState: 'loading', addEventListener() {} }, console };
vm.createContext(context);
vm.runInContext(source + ';window.App = HotelPremierApp;', context);
const app = Object.create(context.window.App.prototype);
app.currentLang = 'en';
app.t = (key, fallback) => fallback || key;
const dish = {id:'test',name:'Paneer Tikka',price:250,image:'assets/photo.jpg',description:'Original description',variants:[{name:'Half',price:150}]};

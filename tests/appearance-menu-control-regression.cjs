const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
let dark=false,listener;
const classes=new Set(),indicator={setAttribute(){}};
const document={readyState:'loading',addEventListener(){},body:{classList:{toggle(name,on){if(on)classes.add(name);else classes.delete(name);},add(){}}},documentElement:{style:{}},querySelector(){return null;},getElementById:id=>id==='theme-toggle-btn'?indicator:null};

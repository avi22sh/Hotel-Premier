const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('index.html','utf8');
const css = fs.readFileSync('royal.css','utf8');
assert.match(html, /name="viewport"[^>]*width=device-width, initial-scale=1\.0, viewport-fit=cover/);
assert.doesNotMatch(html+fs.readFileSync('app.js','utf8'), /maximum-scale|user-scalable=no/);
assert.match(css, /#section-dine #menu-search-input \{ font-size:16px\s*;/);
assert.match(css, /touch-action:manipulation/);
assert.match(html, /Toggle larger text/);
console.log('PASS: accessible viewport, mobile form input sizing and text-size setting retained');

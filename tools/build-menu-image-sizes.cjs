// Mechanical image delivery build: no generation, recolouring, or destructive crops.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const sharp = require(process.env.PREMIER_SHARP_MODULE || 'sharp');
const root = path.resolve(__dirname, '..');
const context = {window:{}};
for (const file of ['data/menu-data.js','data/menu-photos.js']) vm.runInNewContext(fs.readFileSync(path.join(root,file),'utf8'),context);
const menu = context.window.HOTEL_PREMIER_INITIAL_MENU;
const selections = context.window.HOTEL_PREMIER_PHOTOS;
const sources = new Set(menu.map(d => Object.hasOwn(selections,d.id) ? selections[d.id] : d.image).filter(Boolean));
const output = path.join(root,'assets/menu-responsive');
fs.mkdirSync(output,{recursive:true});
(async()=>{
  const manifest = {};
  let originals = 0, thumbnails = 0;
  for (const source of sources) {
    if (!source.startsWith('assets/') || source.includes('..')) throw Error('Not a local photo: '+source);
    const input = path.join(root,source);
    const bytes = fs.readFileSync(input);
    const hash = crypto.createHash('sha256').update(bytes).digest('hex').slice(0,20);
    originals += bytes.length;
    manifest[source] = [];
    for (const size of [240,960]) {
      const relative = `assets/menu-responsive/${hash}-${size}.webp`;
      const target = path.join(root,relative);
      if (!fs.existsSync(target)) await sharp(bytes).rotate().resize({width:size,height:size,fit:'inside',withoutEnlargement:true}).webp({quality:size===240?80:86}).toFile(target);
      const metadata = await sharp(target).metadata();
      manifest[source].push({src:relative,width:metadata.width,height:metadata.height});
      if (size===240) thumbnails += fs.statSync(target).size;
    }
  }
  fs.writeFileSync(path.join(root,'data/menu-image-sizes.js'),'// Generated by tools/build-menu-image-sizes.cjs. Original photo selections remain unchanged.\nwindow.HOTEL_PREMIER_IMAGE_SIZES = '+JSON.stringify(manifest,null,2)+';\n');
  console.log(JSON.stringify({sources:sources.size,originalBytes:originals,thumbnailBytes:thumbnails,reduction:Math.round((1-thumbnails/originals)*100)+'%'}));
})().catch(e=>{console.error(e);process.exitCode=1;});

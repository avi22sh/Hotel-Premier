// Explicit public-file allowlist. Never copy the working tree or owner backups wholesale.
const fs = require('node:fs');
const path = require('node:path');
const { audit } = require('./verify-image-assets.cjs');
const root = path.resolve(__dirname, '..');
const dist = path.join(root, 'dist');
const marker = '.hotel-premier-generated';
const publicFiles = [
 'index.html','admin.html','offline.html','styles.css','royal.css','inline-styles.css','theme-tokens.css','local-admin.css',
 'local-lock.js','photo-storage.js','photo-workflow.js','photo-worker.js','photo-enhance-worker.js','ui-dialogs.js','pwa-updates.js','overlay-manager.js','overlays.css','asset-pipeline.js','public-reviews.js','app.js',
 'admin.js','data-validation.js','admin-layout.js','image-safety.js','publish-bundle.js','content-studio.js','guest-network.js','group-stays.js','menu-structure.js',
 'property-gallery.js','storage.js','vault.js','sw.js','manifest.json','robots.txt','sitemap.xml',
 'data/hotel-data.js','data/menu-data.js','data/menu-photos.js','data/menu-image-sizes.js',
 'data/translations.js','data/guest-localization.js','data/public-reviews.json','data/published-overrides.js','data/legacy-photo-paths.js'
];
const normalize = value => value.replaceAll('\\', '/');
function verifyPublicPath(file) {
 if (!file.startsWith('assets/') || file.split('/').includes('..') || !/\.(?:png|jpe?g|jfif|avif|webp|gif|svg|ico|woff2?)$/i.test(file)) throw Error(`Not a public asset: ${file}`);
 return file;
}
function imageReferences(source) {
 const found = [];
 for (const match of source.matchAll(/(?:["'`(])((?:\.\/)?assets\/[^"'`\n\r<>)]*?\.(?:png|jpe?g|jfif|avif|webp|gif|svg|ico|woff2?))(?:[?#][^"'`\s)]*)?(?=["'`)])/gi)) {
  const file = normalize(decodeURI(match[1].replace(/^\.\//, '').replaceAll('&amp;', '&')));
  if (!file.includes('${')) found.push(verifyPublicPath(file));
 }
 return found;
}
function build() {
 const findings = audit(root);
 if (findings.failures.length) throw Error(JSON.stringify(findings.failures, null, 2));
 if (fs.existsSync(dist) && (fs.lstatSync(dist).isSymbolicLink() || !fs.existsSync(path.join(dist, marker)))) throw Error('Refusing to replace a non-generated dist directory.');
 const assets = new Set();
 for (const file of publicFiles) {
  if (fs.lstatSync(path.join(root, file)).isSymbolicLink()) throw Error(`Symlink not allowed: ${file}`);
  for (const asset of imageReferences(fs.readFileSync(path.join(root, file), 'utf8'))) assets.add(asset);
 }
 // Follow CSS/SVG local image references; include immutable derivatives listed by the photo manifest.
 for (const asset of assets) {
  const source = path.join(root, asset);
  if (!fs.existsSync(source) || fs.lstatSync(source).isSymbolicLink()) throw Error(`Missing or unsafe public asset: ${asset}`);
  if (/\.(?:svg|css)$/.test(asset)) for (const ref of imageReferences(fs.readFileSync(source, 'utf8'))) assets.add(ref);
 }
 const output = path.join(root, `.public-build-${process.pid}-${Date.now()}`);
 fs.mkdirSync(output);
 try {
  for (const file of [...publicFiles, ...assets]) {
   const target = path.join(output, file);
   fs.mkdirSync(path.dirname(target), { recursive: true });
   fs.copyFileSync(path.join(root, file), target);
  }
  fs.copyFileSync(path.join(output, 'index.html'), path.join(output, '404.html'));
  fs.writeFileSync(path.join(output, '.nojekyll'), '');
  fs.writeFileSync(path.join(output, marker), 'Generated by tools/build-public-dist.cjs\n');
  // Only our marked generated output is replaced. Source files and owner uploads are untouched.
  if (fs.existsSync(dist)) fs.rmSync(dist, { recursive: true });
  fs.renameSync(output, dist);
 } catch (error) {
  // Preserve failed staging output for inspection rather than deleting unknown content.
  throw error;
 }
 console.log(`PASS: public dist built (${publicFiles.length + assets.size + 3} files). Tests, tools, backups and base64 dumps excluded.`);
 return { publicFiles, assets: [...assets] };
}
if (require.main === module) build();
module.exports = { build, imageReferences };
